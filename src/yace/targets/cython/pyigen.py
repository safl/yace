"""
The stub of the Cython module, ``<prefix>.pyi``. The stub gives the types of
what the module defines, because a type checker or an editor cannot read the
types from the compiled module. Each annotation is the type that the code
generated by :py:mod:`yace.targets.cython.pyxgen` takes or returns, and the
stub is rendered from the same Renderer as the module.
"""

from typing import Dict, Iterable, List, Optional, Tuple

from yace.ir import decls, types
from yace.ir.semantics import is_void_ptr
from yace.targets.capi import cgen
from yace.targets.idiom import Call, copyable
from yace.targets.python import pygen

from .pyxgen import Renderer

# The methods of every record. A field of the same name hides the method.
PRINTERS = {"to_dict", "fpr", "pr"}

# The Python names the stub uses, each with the module to import the name
# from. "array" is itself a module.
PYTHON = {
    "array": "",
    "bool": "builtins",
    "bytearray": "builtins",
    "bytes": "builtins",
    "classmethod": "builtins",
    "dict": "builtins",
    "float": "builtins",
    "int": "builtins",
    "list": "builtins",
    "memoryview": "builtins",
    "object": "builtins",
    "property": "builtins",
    "str": "builtins",
    "tuple": "builtins",
    "Buffer": "collections.abc",
    "Callable": "collections.abc",
    "Sequence": "collections.abc",
    "IO": "typing",
    "Any": "typing",
    "Self": "typing",
}


def optional(annotation: str, nullable: bool = True) -> str:
    """Return 'annotation', with '| None' added where 'nullable'"""

    if not nullable or annotation == "None" or annotation.endswith("| None"):
        return annotation
    return f"{annotation} | None"


class Stub(object):
    def __init__(self, renderer: Renderer, names: Iterable[str] = ()):
        """The stub of the module that 'renderer' rendered. 'names' are the
        names the module defines besides its functions and classes."""

        self.r = renderer
        # The stub imports a Python name under an alias where the module or one
        # of its classes defines the same name and so would shadow the Python name
        defined = self.defined() | set(names)
        self.py: Dict[str, str] = {}
        for name in PYTHON:
            alias = name
            while alias in defined:
                alias = f"_{alias}"
            self.py[name] = alias

    def defined(self) -> set:
        """The names of the functions and the classes of the module, and of
        the methods and the properties of its classes"""

        r = self.r
        found = {r.class_of(name) for name in r.records}
        found |= {r.handle_class(name) for name in r.classes}
        for call in r.idioms.calls:
            if call.kind == "constructor" and r.usable(call):
                found.add(r.public(call))
        found |= {r.public(call) for call in r.idioms.functions()}
        for name in r.classes:
            for calls in r.idioms.of(name).values():
                found |= {r.public(call, True) for call in calls}
        for record in r.records.values():
            for field in record.fields:
                if field.name:
                    found.add(r.attr(field.name, record))
                    found |= {pygen.accessor(field, mask) for mask in field.masks}
        return found

    def t(self, annotation: str, **parts: str) -> str:
        """Return 'annotation' with each '{name}' replaced by the name under
        which the stub imports the Python name 'name', or by the value of the
        keyword 'name' in 'parts'"""

        return annotation.format(**self.py, **parts)

    def imports(self) -> List[str]:
        """Return the import lines of the stub. A name that the module also
        defines is imported under its alias."""

        def named(name: str) -> str:
            return name if self.py[name] == name else f"{name} as {self.py[name]}"

        lines = [f"import {named('array')}", "import enum"]
        for module in ("builtins", "collections.abc", "typing"):
            names = [n for n, m in PYTHON.items() if m == module]
            if module == "builtins":
                names = [n for n in names if self.py[n] != n]
            if names:
                lines.append(f"from {module} import {', '.join(map(named, names))}")
        return lines

    def is_char_ptr(self, typ) -> bool:
        typ = self.r.resolve(typ)
        return types.is_string(typ) or (
            isinstance(typ, types.Pointer)
            and isinstance(self.r.resolve(typ.to), types.Builtin)
            and self.r.resolve(typ.to).name == "char"
        )

    def builtin(self, typ) -> str:
        """The Python type of a value of the C builtin 'typ'"""

        name = typ.name
        if name == "void":
            return "None"
        if name == "bool":
            return self.py["bool"]
        if name in ("float", "double", "long double"):
            return self.py["float"]
        return self.py["int"]

    def element(self, typ) -> str:
        """The Python type of an element of an array of 'typ' in a buffer"""

        fmt = self.r.fmt(typ)
        if fmt == "?":
            return self.py["bool"]
        if fmt in ("f", "d"):
            return self.py["float"]
        return self.py["int"]

    def value(self, typ, given: bool, copy: bool = False) -> str:
        """Return the Python type of a value of the C type 'typ': with 'given',
        the type that Renderer.to_c() takes, else the type that
        Renderer.to_py() returns"""

        typ = self.r.resolve(typ)
        address = self.t("{int}" if given else "{int} | None")
        if self.is_char_ptr(typ) and not given:
            return self.t("{str} | None")
        if isinstance(typ, types.Pointer):
            cls = self.r.handle_of(typ) or self.r.record_class(typ.to)
            if cls:
                return cls if given else f"{cls} | None"
            to = self.r.resolve(typ.to)
            if copy and not given and isinstance(to, types.Builtin):
                if not is_void_ptr(typ):
                    return f"{self.builtin(to)} | None"
            return address
        if isinstance(typ, types.Array):
            return address
        cls = self.r.record_class(typ)
        if cls:
            return cls
        if isinstance(typ, types.Builtin):
            return self.builtin(typ)
        if isinstance(typ, types.EnumRef):
            return self.py["int"]
        return self.py["Any"]

    # Functions

    def callback(self, typ) -> str:
        """Return the Callable type of a closure given for the callback type
        'typ'"""

        fntype = self.r.resolve(typ).to
        params = [
            self.value(p.typ, given=False)
            for p in fntype.params
            if not is_void_ptr(p.typ)
        ]
        ret = self.value(fntype.ret, given=True)
        return self.t(
            "{Callable}[[{params}], {ret}]", params=", ".join(params), ret=ret
        )

    def sequence(self, call: Call, arg) -> str:
        """Return the type that Renderer.sequence() accepts for the sequence
        'arg'"""

        param = self.r.idioms.decl(call.function).params[arg.index]
        typ = self.r.resolve(param.typ)
        elem = typ.to if isinstance(typ, types.Pointer) else typ.of
        cls = self.r.record_class(elem)
        if cls:
            return self.t("{Sequence}[{cls}]", cls=cls)
        if types.is_string(self.r.resolve(elem)):
            return self.t("{Sequence}[{str} | {bytes}]")
        if is_void_ptr(typ):
            return self.py["Buffer"]
        items = self.py["list" if param.direction == "inout" else "Sequence"]
        return self.t(
            "{Buffer} | {items}[{item}]", items=items, item=self.element(elem)
        )

    def param(self, call: Call, arg) -> str:
        typ = self.r.idioms.decl(call.function).params[arg.index].typ
        if arg.kind == "string":
            found = self.t("{str} | {bytes}")
        elif arg.kind == "sequence":
            found = self.sequence(call, arg)
        elif arg.kind == "callback":
            found = self.callback(typ)
        elif arg.kind == "capacity":
            found = self.py["int"]
        else:
            found = self.value(typ, given=True)
        return optional(found, arg.nullable)

    def results(self, call: Call) -> str:
        """Return the type of what Renderer.results() makes the function of
        'call' return"""

        found: List[str] = []
        counted = call.returns == "count"
        for out in call.outs:
            if out.kind == "array":
                if not out.count:
                    counted = False
                elem = out.typ
                cls = self.r.record_class(elem)
                if is_void_ptr(types.Pointer(to=elem)):
                    found.append(self.py["bytearray"])
                elif cls:
                    found.append(self.t("{list}[{cls}]", cls=cls))
                elif types.is_string(self.r.resolve(elem)):
                    found.append(self.t("{list}[{str} | None]"))
                else:
                    # array.array has no bool code, so an array of bool has int
                    # elements
                    floating = self.element(elem) == self.py["float"]
                    item = self.py["float" if floating else "int"]
                    found.append(self.t("{array}.array[{item}]", item=item))
            elif out.kind == "handle":
                address = self.t("{int} | None")
                found.append(self.r.handle_of(out.typ) or address)
            elif out.kind == "record":
                found.append(self.r.record_class(out.typ) or self.py["Any"])
            else:
                found.append(self.value(out.typ, given=False, copy=True))
        if counted:
            found.append(self.py["int"])
        if call.returns in ("value", "string", "handle"):
            found.append(self.value(call.ret, given=False))
        elif call.returns == "pointer":
            copy = copyable(self.r.model, call.ret.to)
            found.append(self.value(call.ret, given=False, copy=copy))
        if not found:
            return "None"
        if len(found) == 1:
            return found[0]
        return self.t("{tuple}[{found}]", found=", ".join(found))

    def function(self, call: Call, indent: str = "", self_: bool = False) -> str:
        names = self.r.params(call)
        params = ["self"] if self_ else []
        for name, arg in zip(names, self.r.visible(call)):
            bare = name.removesuffix("=None")
            default = " = None" if name.endswith("=None") else ""
            params.append(f"{bare}: {self.param(call, arg)}{default}")
        name = self.r.public(call, self_)
        lines = [
            f"{indent}def {name}({', '.join(params)}) -> {self.results(call)}:",
            f"{indent}    {self.r.doc(call, indent + '    ')}",
        ]
        return "\n".join(lines)

    def handle(self, record: str) -> str:
        calls = self.r.idioms.of(record)
        cls = self.r.handle_class(record)
        entity = self.r.model.find(record, decls.RECORDS)
        doc = pygen.docstring(entity.doc, "    ") or record
        lines = [
            "@disjoint_base",
            f"class {cls}:",
            f"    {pygen.quoted(doc, '    ')}",
            "",
            f"    def __enter__(self) -> {self.py['Self']}: ...",
            f"    def __exit__(self, *exc: {self.py['object']}) -> None: ...",
        ]
        for call in calls["method"]:
            lines.append(self.function(call, "    ", self_=True))
        destructor = calls["destructor"][0] if calls["destructor"] else None
        if destructor:
            lines.append(self.function(destructor, "    ", self_=True))
        return "\n".join(lines)

    # Records

    def field(self, record, field: decls.Field) -> Optional[Tuple[str, str]]:
        """Return the type that the property of 'field' returns and the type
        that its setter takes, following Renderer.field(), or None for a field
        the module does not bind"""

        if self.r.field(record, field) is None:
            return None
        typ = self.r.resolve(field.typ)
        if isinstance(typ, types.Array):
            dims = 0
            elem = typ
            while isinstance(elem, types.Array):
                dims += 1
                elem = self.r.resolve(elem.of)
            cls = self.r.record_class(elem)
            given = self.t("{Sequence}[")
            if dims == 1 and isinstance(elem, types.Builtin) and elem.name == "char":
                return self.py["bytes"], self.t("{str} | {bytes}")
            if cls:
                return self.t("{tuple}[{cls}, ...]", cls=cls), f"{given}{cls}]"
            item = self.element(elem)
            if record.packed:
                return self.t("{list}[{item}]", item=item), f"{given}{item}]"
            return self.py["memoryview"], given * dims + item + "]" * dims
        if isinstance(typ, types.Record):
            cls = self.r.record_class(typ) or self.py["Any"]
            return cls, cls
        if self.is_char_ptr(field.typ):
            return self.t("{str} | None"), self.t("{str} | {bytes} | None")
        if isinstance(typ, types.Pointer):
            return self.t("{int} | None"), self.t("{int} | None")
        if isinstance(typ, types.Builtin) and typ.name == "char":
            return self.py["bytes"], self.t("{bytes} | {int}")
        found = self.value(typ, given=True)
        return found, found

    def prop(self, name: str, get: str, put: str, doc: str) -> List[str]:
        ignore = "  # type: ignore[override]" if name in PRINTERS else ""
        return [
            f"    @{self.py['property']}{ignore}",
            f"    def {name}(self) -> {get}:",
            f"        {doc}",
            f"    @{name}.setter",
            f"    def {name}(self, value: {put}) -> None: ...",
        ]

    def record(self, record) -> str:
        cls = self.r.class_of(record.name)
        summary = pygen.docstring(record.doc, "    ") or (
            f"{cgen.tag(record)} {record.name}"
        )
        named = [f for f in record.fields if f.name and not self.r.flexible(f)]
        typed: Dict[str, Tuple[str, str]] = {}
        for field in named:
            found = self.field(record, field)
            if found is not None:
                typed[field.name] = found
        fields = [f for f in named if f.name in typed]
        args = [
            f"{self.r.attr(f.name, record)}: {optional(typed[f.name][1])} = None"
            for f in fields
        ]
        params = ", ".join([self.r.this(record), *args])
        lines = [
            "@disjoint_base",
            f"class {cls}(_Record):",
            f"    {pygen.quoted(summary, '    ')}",
            "",
            f"    def __init__({params}) -> None: ...",
        ]
        for field in fields:
            get, put = typed[field.name]
            brief = " ".join((field.doc.brief or field.name).split())
            doc = pygen.quoted(brief, "        ")
            lines += self.prop(self.r.attr(field.name, record), get, put, doc)
        for field in fields:
            for mask in field.masks:
                doc = pygen.docstring(mask.doc, "        ") or mask.name
                doc = pygen.quoted(doc, "        ")
                name = pygen.accessor(field, mask)
                lines += self.prop(name, self.py["int"], self.py["int"], doc)
        return "\n".join(lines)

    def render(self) -> dict:
        """Return the records, handles and functions of the stub. Call render()
        after Renderer.render(), which decides which handles have a class."""

        r = self.r
        functions = []
        for call in r.idioms.calls:
            if call.kind == "constructor" and r.usable(call):
                functions.append(self.function(call))
        functions += [self.function(c) for c in r.idioms.functions()]
        return {
            "py": self.py,
            "imports": self.imports(),
            "records": [self.record(rec) for rec in r.records.values()],
            "handles": [self.handle(name) for name in r.classes],
            "functions": functions,
        }
